// Writes assets/js/config.js from .env (or from real environment variables, e.g. in CI).
// Usage: node scripts/build-config.mjs
// No dependencies. Real environment variables win over values in .env.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const envFile = join(root, ".env");
const vals = {};

if (existsSync(envFile)) {
  for (const line of readFileSync(envFile, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m) vals[m[1]] = m[2].replace(/^(['"])(.*)\1$/, "$2");
  }
}
const get = (k) => process.env[k] ?? vals[k] ?? "";

const api = get("SB_API_URL").replace(/\/+$/, "");
const gaId = get("SB_GA_ID");

const out = `/* GENERATED by scripts/build-config.mjs from .env. Edit .env, then run: node scripts/build-config.mjs
   api : Form API base URL (no trailing slash). Empty = demo mode (no network calls, preview data only).
   Endpoints used (see CHANGELOG): POST /v1/token/decrypt, GET /v1/member,
   POST /v1/register, POST /v1/lead, POST /v1/stock. Auth: header X-Form-Token = ?encrypted_token= from the link.
   gaId: GA4 measurement ID (analytics.js). Empty = analytics off. */
var SB_CONFIG = {
  api: ${JSON.stringify(api)},
  gaId: ${JSON.stringify(gaId)},
};
`;

writeFileSync(join(root, "assets", "js", "config.js"), out);
console.log(`config.js written (api: ${api || "(demo mode)"}, gaId: ${gaId || "(off)"})`);
